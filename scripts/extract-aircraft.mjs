/**
 * Lifts the legacy animated Falcon 50 views (FalconSideView / FalconTopView)
 * into src/features/phases/aircraftView.js. They are plain React.createElement
 * output that reads a flight-state object `s`, so they drop directly into the
 * new PhasesScreen and animate with the flight (gear, flaps, slats, engines,
 * lights, A/P, reverser).
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = resolve(__dirname, "..");
const src = readFileSync(resolve(root, "legacy/index.html"), "utf8");

function extractExpr(name) {
  const decl = `var ${name}=`;
  const at = src.indexOf(decl);
  if (at === -1) throw new Error(`${name} not found`);
  let i = at + decl.length;
  const start = i;
  let c = 0, p = 0, sq = 0, str = null;
  for (; i < src.length; i++) {
    const ch = src[i];
    if (str) { if (ch === "\\") { i++; continue; } if (ch === str) str = null; continue; }
    if (ch === '"' || ch === "'" || ch === "`") { str = ch; continue; }
    if (ch === "{") c++; else if (ch === "}") c--;
    else if (ch === "(") p++; else if (ch === ")") p--;
    else if (ch === "[") sq++; else if (ch === "]") sq--;
    else if (ch === ";" && !c && !p && !sq) return src.slice(start, i);
  }
  throw new Error(`${name}: no terminator`);
}

const names = ["FalconSideView", "FalconTopView"];
const parts = names.map((n) => `var ${n} = ${extractExpr(n)};`);

const out = `/* eslint-disable */
// AUTO-GENERATED by scripts/extract-aircraft.mjs — do not edit by hand.
// Verbatim lift of the legacy animated Falcon 50 views (React createElement).
import React from "react";

${parts.join("\n\n")}

export { FalconSideView, FalconTopView };
`;

const dir = resolve(root, "src/features/phases");
mkdirSync(dir, { recursive: true });
writeFileSync(resolve(dir, "aircraftView.js"), out);
console.log(`wrote src/features/phases/aircraftView.js (${names.join(", ")})`);
