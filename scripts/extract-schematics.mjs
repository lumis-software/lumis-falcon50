/**
 * Lifts the interactive system-schematic engine out of the legacy single-file
 * app and emits:
 *   - src/features/systems/schematics/engine.js  (helpers + system defs +
 *     AudioController + SYS_NARRATION + INTERACTIVE map, verbatim React code)
 *   - src/features/systems/schematics/handbook.ts (map of CAE handbook image URLs)
 *   - public/handbook/<key>.png  (decoded CAE handbook diagrams)
 *
 * The legacy code is already React.createElement output, so lifting it
 * preserves the diagrams exactly. We only re-author the wrapper UI in TSX.
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = resolve(__dirname, "..");
const src = readFileSync(resolve(root, "legacy/index.html"), "utf8");

const outDir = resolve(root, "src/features/systems/schematics");
mkdirSync(outDir, { recursive: true });
const imgDir = resolve(root, "public/handbook");
mkdirSync(imgDir, { recursive: true });

/** Extract the balanced RHS expression of `var NAME=...;` as raw text. */
function extractExpr(name) {
  const decl = `var ${name}=`;
  const at = src.indexOf(decl);
  if (at === -1) throw new Error(`${name} not found`);
  let i = at + decl.length;
  const start = i;
  let curly = 0;
  let paren = 0;
  let square = 0;
  let inStr = null;
  for (; i < src.length; i++) {
    const c = src[i];
    if (inStr) {
      if (c === "\\") {
        i++;
        continue;
      }
      if (c === inStr) inStr = null;
      continue;
    }
    if (c === '"' || c === "'" || c === "`") {
      inStr = c;
      continue;
    }
    if (c === "{") curly++;
    else if (c === "}") curly--;
    else if (c === "(") paren++;
    else if (c === ")") paren--;
    else if (c === "[") square++;
    else if (c === "]") square--;
    else if (c === ";" && !curly && !paren && !square) {
      return src.slice(start, i);
    }
  }
  throw new Error(`${name}: no terminating semicolon at depth 0`);
}

// --- 1. CAE handbook images: decode base64 -> PNG files -------------------
const handbookExpr = extractExpr("HANDBOOK_IMG");
// eslint-disable-next-line no-new-func
const HANDBOOK_IMG = Function(`"use strict";return (${handbookExpr});`)();
const handbookKeys = [];
for (const [key, uri] of Object.entries(HANDBOOK_IMG)) {
  const m = /^data:image\/png;base64,(.+)$/s.exec(uri);
  if (!m) {
    console.warn(`  ! handbook ${key}: not a png data uri, skipping`);
    continue;
  }
  writeFileSync(resolve(imgDir, `${key}.png`), Buffer.from(m[1], "base64"));
  handbookKeys.push(key);
  console.log(`  ✓ handbook/${key}.png`);
}

const handbookTs = `// AUTO-GENERATED by scripts/extract-schematics.mjs — do not edit.
// CAE Falcon 50 Operating Handbook schematics (Rev 1 Aug 2025), served as
// static images so they are cached by the service worker and kept out of JS.
const base = import.meta.env.BASE_URL;
export const HANDBOOK_IMG: Record<string, string> = {
${handbookKeys.map((k) => `  ${k}: base + "handbook/${k}.png",`).join("\n")}
};
`;
writeFileSync(resolve(outDir, "handbook.ts"), handbookTs);

